var (
	GenerativeAiModelDiscoveryDataSourceRepresentation = map[string]interface{}{
		"compartment_id": acctest.Representation{RepType: acctest.Required, Create: `${var.compartment_id}`},
	}
)

// issue-routing-tag: generative_ai/default
func TestGenerativeAiModelDiscoveryDataSource_basic(t *testing.T) {
	httpreplay.SetScenario("TestGenerativeAiModelDiscoveryDataSource_basic")
	defer httpreplay.SaveScenario()

	config := acctest.ProviderTestConfig()

	compartmentId := utils.GetEnvSettingWithBlankDefault("compartment_ocid")
	compartmentIdVariableStr := fmt.Sprintf("variable \"compartment_id\" { default = \"%s\" }\n", compartmentId)

	datasourceName := "data.oci_generative_ai_model_discoveries.test_model_discoveries"

	acctest.SaveConfigContent("", "", "", t)

	acctest.ResourceTest(t, nil, []resource.TestStep{
		// verify datasource
		{
			Config: config +
				acctest.GenerateDataSourceFromRepresentationMap("oci_generative_ai_model_discoveries", "test_model_discoveries", acctest.Required, acctest.Create, GenerativeAiModelDiscoveryDataSourceRepresentation) +
				compartmentIdVariableStr,
			Check: acctest.ComposeAggregateTestCheckFuncWrapper(
				resource.TestCheckResourceAttr(datasourceName, "compartment_id", compartmentId),
				resource.TestCheckResourceAttr(datasourceName, "model_discovery_collection.#", "1"),
				resource.TestCheckResourceAttrSet(datasourceName, "model_discovery_collection.0.items.#"),
			),
		},
	})
}
